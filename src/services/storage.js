// ============================================================================
// MODIFICAR CONFIGURACIÓN DE INGRESO RECURRENTE
// ============================================================================
export const updateRecurringIncomeConfig = (data, { amount, period, enabled }) => {
  const current = data.recurring_income || {};
  const newAmount = amount !== undefined ? parseFloat(amount) : current.amount;
  const newPeriod = period !== undefined ? period : current.period;
  const newEnabled = enabled !== undefined ? enabled : current.enabled;

  // Recalcular próxima fecha si cambió
  let nextDate = new Date();
  if (newPeriod === 'WEEKLY') {
    nextDate.setDate(nextDate.getDate() + 7);
  } else if (newPeriod === 'BIWEEKLY') {
    nextDate.setDate(nextDate.getDate() + 15);
  } else {
    nextDate.setMonth(nextDate.getMonth() + 1);
  }

  const updatedRecurring = {
    ...current,
    amount: newAmount,
    period: newPeriod,
    enabled: newEnabled,
    next_date: getLocalDateString(nextDate),
  };

  return {
    ...data,
    recurring_income: updatedRecurring,
  };
};

