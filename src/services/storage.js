// RECALCULAR ESTADO DE ÁNIMO Y RACHA AL INICIAR
// ============================================================================
export const evaluateStreakAndMood = (data, referenceDate = new Date()) => {
  if (!data || !data.pet) return data;

  const todayStr = getLocalDateString(referenceDate);
  const streak = { ...(data.streak || { current_days: 0, best_days: 0, last_expense_date: null }) };
  const pet = { ...data.pet };

  if (streak.last_expense_date) {
    const lastDate = new Date(streak.last_expense_date);
    const diffMs = referenceDate.getTime() - lastDate.getTime();
    const diffDays = Math.floor(diffMs / (1000 * 60 * 60 * 24));
    const diffHours = diffMs / (1000 * 60 * 60);

    // Si pasaron más de 1 día calendario completo sin registrar gasto, la racha vuelve a 0
    if (diffDays > 1 && streak.last_expense_date !== todayStr) {
      streak.current_days = 0;
    }

    // Estado de ánimo: si pasaron más de 24h desde el último gasto -> SAD
    if (diffHours >= GAME_CONFIG.SAD_THRESHOLD_HOURS) {
      pet.mood = 'SAD';
    } else {
      pet.mood = 'HAPPY';
    }
  }

  return {
    ...data,
    streak,
    pet,
  };
};

