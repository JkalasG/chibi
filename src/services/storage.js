import AsyncStorage from '@react-native-async-storage/async-storage';
import { GAME_CONFIG, PET_STAGES } from '../config/gameConfig';

const STORAGE_KEY = '@metafin_save_v1';

// Helper de fechas ISO sin hora (YYYY-MM-DD)
export const getLocalDateString = (dateObj = new Date()) => {
  const year = dateObj.getFullYear();
  const month = String(dateObj.getMonth() + 1).padStart(2, '0');
  const day = String(dateObj.getDate()).padStart(2, '0');
  return `${year}-${month}-${day}`;
};

// Generador de UUIDs sencillos para IDs locales
export const generateId = () => {
  return `${Date.now()}-${Math.random().toString(36).substr(2, 9)}`;
};

// Determinar la etapa de la mascota según su nivel
export const getStageForLevel = (level) => {
  if (level <= 1) return PET_STAGES.EGG.name;
  if (level <= 5) return PET_STAGES.BABY.name;
  if (level <= 10) return PET_STAGES.JUVENILE.name;
  return PET_STAGES.LEGEND.name;
};

// Estado inicial por defecto
export const INITIAL_DATA = {
  schema_version: 1,
  user: null, // { id, full_name, alias, email, phone_country_code, phone_number, city, currency: 'Bs', onboarding_step: 'REGISTER' }
  pet: null,  // { id, name, species: 'DOG', level: 1, current_xp: 0, total_xp: 0, stage: 'Huevo', mood: 'HAPPY', hatched_at: null }
  recurring_income: null, // { amount: 2500, period: 'MONTHLY', start_date: '...', next_date: '...', enabled: true }
  streak: {
    current_days: 0,
    best_days: 0,
    last_expense_date: null,
  },
  transactions: [],
};

// Cargar datos desde almacenamiento local
export const loadGameData = async () => {
  try {
    const raw = await AsyncStorage.getItem(STORAGE_KEY);
    if (!raw) return { ...INITIAL_DATA };
    const parsed = JSON.parse(raw);
    return { ...INITIAL_DATA, ...parsed };
  } catch (error) {
    console.error('Error cargando datos de MetaFin:', error);
    return { ...INITIAL_DATA };
  }
};

// Guardar datos en almacenamiento local
export const saveGameData = async (data) => {
  try {
    await AsyncStorage.setItem(STORAGE_KEY, JSON.stringify(data));
    return true;
  } catch (error) {
    console.error('Error guardando datos de MetaFin:', error);
    return false;
  }
};

// Borrar y reiniciar datos
export const resetGameData = async () => {
  try {
    await AsyncStorage.removeItem(STORAGE_KEY);
    return { ...INITIAL_DATA };
  } catch (error) {
    console.error('Error reiniciando datos:', error);
    return { ...INITIAL_DATA };
  }
};

