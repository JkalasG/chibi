// REGISTRO DE GASTO
// ============================================================================
export const registerExpense = (data, { amount, categoryId, note = '', referenceDate = new Date() }) => {
  const todayStr = getLocalDateString(referenceDate);
  const streak = { ...(data.streak || { current_days: 0, best_days: 0, last_expense_date: null }) };
  const pet = { ...data.pet };

  // Cálculo de racha:
  // Si ya se registró gasto hoy: la racha no cambia
  // Si el último gasto fue ayer: racha + 1
  // Si no: racha arranca en 1
  if (streak.last_expense_date === todayStr) {
    // Ya registró hoy, mantiene la racha
  } else if (streak.last_expense_date) {
    const yesterday = new Date(referenceDate);
    yesterday.setDate(yesterday.getDate() - 1);
    const yesterdayStr = getLocalDateString(yesterday);

    if (streak.last_expense_date === yesterdayStr) {
      streak.current_days = (streak.current_days || 0) + 1;
    } else {
      streak.current_days = 1;
    }
  } else {
    streak.current_days = 1;
  }

  streak.last_expense_date = todayStr;
  streak.best_days = Math.max(streak.best_days || 0, streak.current_days);

  // Bono de racha: XP = 10 + (díasRacha - 1)
  const streakBonus = Math.max(0, (streak.current_days - 1) * GAME_CONFIG.STREAK_BONUS_PER_DAY);
  const xpAwarded = GAME_CONFIG.BASE_XP + streakBonus;

  // Actualizar XP de la mascota
  let currentXp = (pet.current_xp || 0) + xpAwarded;
  let level = pet.level || 1;
  let leveledUp = false;

  while (currentXp >= GAME_CONFIG.XP_PER_LEVEL) {
    currentXp -= GAME_CONFIG.XP_PER_LEVEL;
    level += 1;
    leveledUp = true;
  }

  pet.current_xp = currentXp;
  pet.level = level;
  pet.total_xp = (pet.total_xp || 0) + xpAwarded;
  pet.stage = getStageForLevel(level);
  pet.mood = 'HAPPY'; // Registrar gasto alegra de inmediato a la mascota

  const newTx = {
    id: generateId(),
    type: 'EXPENSE',
    category_id: categoryId,
    source: 'MANUAL',
    amount: parseFloat(amount),
    note: note || '',
    occurred_at: referenceDate.toISOString(),
    xp_awarded: xpAwarded,
    created_at: referenceDate.toISOString(),
  };

  const updatedData = {
    ...data,
    streak,
    pet,
    transactions: [newTx, ...(data.transactions || [])],
  };

  return {
    data: updatedData,
    xpAwarded,
    leveledUp,
    newLevel: level,
    newStage: pet.stage,
  };
};

