// PROCESAMIENTO DE INGRESOS AUTOMÁTICOS
// ============================================================================
export const processAutomaticIncomes = (data, referenceDate = new Date()) => {
  if (!data || !data.recurring_income || !data.recurring_income.enabled) {
    return { data, autoGeneratedCount: 0, autoGeneratedAmount: 0 };
  }

  const recurring = { ...data.recurring_income };
  if (!recurring.next_date) {
    return { data, autoGeneratedCount: 0, autoGeneratedAmount: 0 };
  }

  let nextDate = new Date(recurring.next_date);
  const now = new Date(referenceDate);
  const newTransactions = [...(data.transactions || [])];
  let autoCount = 0;
  let totalAmount = 0;

  // Si la fecha actual ya superó o igualó la próxima fecha de ingreso automático
  while (nextDate <= now) {
    const occurredAt = nextDate.toISOString();
    const autoTx = {
      id: generateId(),
      type: 'INCOME',
      category_id: null,
      source: 'AUTO',
      amount: recurring.amount,
      note: 'Ingreso recurrente automático',
      occurred_at: occurredAt,
      xp_awarded: 0,
      created_at: occurredAt,
    };

    newTransactions.unshift(autoTx);
    autoCount += 1;
    totalAmount += recurring.amount;

    // Avanzar siguiente periodo
    if (recurring.period === 'WEEKLY') {
      nextDate.setDate(nextDate.getDate() + 7);
    } else if (recurring.period === 'BIWEEKLY') {
      nextDate.setDate(nextDate.getDate() + 15);
    } else {
      // Monthly: mismo día del siguiente mes
      nextDate.setMonth(nextDate.getMonth() + 1);
    }
  }

  recurring.next_date = getLocalDateString(nextDate);

  const updatedData = {
    ...data,
    recurring_income: recurring,
    transactions: newTransactions,
  };

  return {
    data: updatedData,
    autoGeneratedCount: autoCount,
    autoGeneratedAmount: totalAmount,
  };
};

