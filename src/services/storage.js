export const devToggleMood = (data) => {
  const pet = { ...data.pet };
  pet.mood = pet.mood === 'HAPPY' ? 'SAD' : 'HAPPY';
  return { ...data, pet };
};

export const devAdvanceDay = (data) => {
  // Simular que pasó un día
  const streak = { ...(data.streak || { current_days: 0, best_days: 0, last_expense_date: null }) };
  if (streak.last_expense_date) {
    const prev = new Date(streak.last_expense_date);
    prev.setDate(prev.getDate() - 1);
    streak.last_expense_date = getLocalDateString(prev);
  }
  return evaluateStreakAndMood({ ...data, streak });
};
