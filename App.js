import React, { useState, useEffect } from 'react';
import {
  StyleSheet,
  SafeAreaView,
  KeyboardAvoidingView,
  Platform,
  StatusBar,
  View,
} from 'react-native';

// Servicios y Configuración
import {
  loadGameData,
  saveGameData,
  resetGameData,
  processAutomaticIncomes,
  evaluateStreakAndMood,
  registerExpense,
  registerManualIncome,
  updateRecurringIncomeConfig,
  devAddXP,
  devToggleMood,
  devAdvanceDay,
  generateId,
  getLocalDateString,
} from './src/services/storage';

// Pantallas
import SplashScreen from './src/screens/SplashScreen';
import OnboardingScreen from './src/screens/OnboardingScreen';
import HatchingScreen from './src/screens/HatchingScreen';
import DashboardScreen from './src/screens/DashboardScreen';
import IncomeScreen from './src/screens/IncomeScreen';
import HistoryScreen from './src/screens/HistoryScreen';
import HelpScreen from './src/screens/HelpScreen';

// Componentes UI
import BottomNavBar from './src/components/UI/BottomNavBar';

export default function App() {
  const [appState, setAppState] = useState('SPLASH'); // 'SPLASH' | 'ONBOARDING' | 'HATCHING' | 'MAIN'
  const [activeTab, setActiveTab] = useState('DASHBOARD'); // 'DASHBOARD' | 'INCOME' | 'HISTORY' | 'HELP'
  const [gameData, setGameData] = useState(null);
  const [autoIncomeAlert, setAutoIncomeAlert] = useState(null);
  const [firstTimeHighlight, setFirstTimeHighlight] = useState(false);

  // Carga inicial al arrancar
  useEffect(() => {
    const initApp = async () => {
      const loaded = await loadGameData();

      // Procesar posibles ingresos recurrentes que hayan vencido mientras la app estaba cerrada
      const { data: withAutoIncomes, autoGeneratedCount, autoGeneratedAmount } =
        processAutomaticIncomes(loaded);

      // Evaluar racha y estado de ánimo según última fecha
      const evaluated = evaluateStreakAndMood(withAutoIncomes);

      setGameData(evaluated);
      await saveGameData(evaluated);

      if (autoGeneratedCount > 0) {
        setAutoIncomeAlert({
          count: autoGeneratedCount,
          amount: autoGeneratedAmount,
        });
      }
    };

    initApp();
  }, []);

  // Decisión de ruta al terminar el Splash
  const handleSplashFinish = () => {
    if (!gameData || !gameData.user) {
      setAppState('ONBOARDING');
    } else if (gameData.user.onboarding_step !== 'DONE') {
      setAppState('HATCHING');
    } else {
      setAppState('MAIN');
    }
  };

  // Onboarding completado -> ir a Eclosión
  const handleOnboardingComplete = async ({ user, pet }) => {
    const updated = {
      ...gameData,
      user,
      pet,
    };
    setGameData(updated);
    await saveGameData(updated);
    setAppState('HATCHING');
  };

  // Eclosión completada -> ir a Dashboard
  const handleHatchingComplete = async ({ initialIncome, incomePeriod, firstExpense }) => {
    const now = new Date();
    const todayStr = getLocalDateString(now);

    // Próxima fecha según periodo
    const nextDate = new Date(now);
    if (incomePeriod === 'WEEKLY') nextDate.setDate(nextDate.getDate() + 7);
    else if (incomePeriod === 'BIWEEKLY') nextDate.setDate(nextDate.getDate() + 15);
    else nextDate.setMonth(nextDate.getMonth() + 1);

    const recurringIncome = {
      amount: initialIncome,
      period: incomePeriod,
      start_date: todayStr,
      next_date: getLocalDateString(nextDate),
      enabled: true,
    };

    // Transacción 1: Ingreso inicial
    const initialIncomeTx = {
      id: generateId(),
      type: 'INCOME',
      category_id: null,
      source: 'MANUAL',
      amount: initialIncome,
      note: 'Ingreso inicial de eclosión',
      occurred_at: now.toISOString(),
      xp_awarded: 10,
      created_at: now.toISOString(),
    };

    // Transacción 2: Primer gasto
    const firstExpenseTx = {
      id: generateId(),
      type: 'EXPENSE',
      category_id: firstExpense.category,
      source: 'MANUAL',
      amount: firstExpense.amount,
      note: 'Primer gasto de nacimiento',
      occurred_at: now.toISOString(),
      xp_awarded: 10,
      created_at: now.toISOString(),
    };

    const updatedUser = {
      ...gameData.user,
      onboarding_step: 'DONE',
    };

    const updatedPet = {
      ...gameData.pet,
      level: 2,
      current_xp: 0,
      total_xp: 20,
      stage: 'Bebé',
      mood: 'HAPPY',
      hatched_at: now.toISOString(),
    };

    const updatedStreak = {
      current_days: 1,
      best_days: 1,
      last_expense_date: todayStr,
    };

    const updated = {
      ...gameData,
      user: updatedUser,
      pet: updatedPet,
      recurring_income: recurringIncome,
      streak: updatedStreak,
      transactions: [firstExpenseTx, initialIncomeTx],
    };

    setGameData(updated);
    await saveGameData(updated);
    setFirstTimeHighlight(true);
    setAppState('MAIN');
  };

  // Registrar un gasto desde el Dashboard
  const handleRegisterExpense = async ({ amount, categoryId, note }) => {
    const result = registerExpense(gameData, { amount, categoryId, note });
    setGameData(result.data);
    await saveGameData(result.data);
    if (firstTimeHighlight) setFirstTimeHighlight(false);
    return result;
  };

  // Registrar ingreso manual desde la pantalla de Ingresos
  const handleRegisterManualIncome = async ({ amount, note }) => {
    const result = registerManualIncome(gameData, { amount, note });
    setGameData(result.data);
    await saveGameData(result.data);
    return result;
  };

  // Actualizar configuración del ingreso recurrente
  const handleUpdateRecurringIncome = async (config) => {
    const updated = updateRecurringIncomeConfig(gameData, config);
    setGameData(updated);
    await saveGameData(updated);
  };

  // Eliminar movimiento
  const handleDeleteTransaction = async (id) => {
    const updatedTransactions = (gameData.transactions || []).filter((t) => t.id !== id);
    const updated = {
      ...gameData,
      transactions: updatedTransactions,
    };
    setGameData(updated);
    await saveGameData(updated);
  };

  // ============================================================================
  // DEV TOOLS / DEMO CONTROLS (F-49)
  // ============================================================================
  const handleDevAddXP = async () => {
    const { data: updated } = devAddXP(gameData, 25);
    setGameData(updated);
    await saveGameData(updated);
  };

  const handleDevToggleMood = async () => {
    const updated = devToggleMood(gameData);
    setGameData(updated);
    await saveGameData(updated);
  };

  const handleDevAdvanceDay = async () => {
    const advanced = devAdvanceDay(gameData);
    const { data: withAuto } = processAutomaticIncomes(advanced);
    setGameData(withAuto);
    await saveGameData(withAuto);
  };

  const handleDevResetApp = async () => {
    const fresh = await resetGameData();
    setGameData(fresh);
    setAutoIncomeAlert(null);
    setAppState('ONBOARDING');
    setActiveTab('DASHBOARD');
  };

  const handleRepeatTutorial = () => {
    setAppState('HATCHING');
  };

  return (
    <SafeAreaView style={styles.safeArea}>
      <StatusBar barStyle="dark-content" backgroundColor="#FDFBF7" />
      <KeyboardAvoidingView
        behavior={Platform.OS === 'ios' ? 'padding' : undefined}
        style={{ flex: 1 }}
      >
        <View style={styles.appContainer}>
          {/* PANTALLA DE CARGA / SPLASH */}
          {appState === 'SPLASH' && (
            <SplashScreen onFinish={handleSplashFinish} />
          )}

          {/* ONBOARDING / REGISTRO */}
          {appState === 'ONBOARDING' && (
            <OnboardingScreen onComplete={handleOnboardingComplete} />
          )}

          {/* ECLOSIÓN Y TUTORIAL */}
          {appState === 'HATCHING' && (
            <HatchingScreen
              user={gameData?.user}
              pet={gameData?.pet}
              initialStep={gameData?.user?.onboarding_step || 'HATCH_INCOME'}
              onCompleteHatching={handleHatchingComplete}
            />
          )}

          {/* APLICACIÓN PRINCIPAL (CON NAVEGACIÓN INFERIOR) */}
          {appState === 'MAIN' && (
            <View style={{ flex: 1 }}>
              <View style={{ flex: 1 }}>
                {activeTab === 'DASHBOARD' && (
                  <DashboardScreen
                    data={gameData}
                    onRegisterExpense={handleRegisterExpense}
                    autoIncomeNotification={autoIncomeAlert}
                    highlightCategories={firstTimeHighlight}
                    onNavigateToHistory={() => setActiveTab('HISTORY')}
                  />
                )}

                {activeTab === 'INCOME' && (
                  <IncomeScreen
                    data={gameData}
                    onRegisterManualIncome={handleRegisterManualIncome}
                    onUpdateRecurringIncome={handleUpdateRecurringIncome}
                  />
                )}

                {activeTab === 'HISTORY' && (
                  <HistoryScreen
                    transactions={gameData?.transactions || []}
                    onDeleteTransaction={handleDeleteTransaction}
                  />
                )}

                {activeTab === 'HELP' && (
                  <HelpScreen
                    onRepeatTutorial={handleRepeatTutorial}
                    onDevAddXP={handleDevAddXP}
                    onDevToggleMood={handleDevToggleMood}
                    onDevAdvanceDay={handleDevAdvanceDay}
                    onDevResetApp={handleDevResetApp}
                  />
                )}
              </View>

              {/* BARRA DE NAVEGACIÓN INFERIOR (4 SECCIONES) */}
              <BottomNavBar
                activeTab={activeTab}
                onSelectTab={(tab) => {
                  if (autoIncomeAlert) setAutoIncomeAlert(null);
                  setActiveTab(tab);
                }}
              />
            </View>
          )}
        </View>
      </KeyboardAvoidingView>
    </SafeAreaView>
  );
}

const styles = StyleSheet.create({
  safeArea: {
    flex: 1,
    backgroundColor: '#FDFBF7',
  },
  appContainer: {
    flex: 1,
    backgroundColor: '#FDFBF7',
  },
});